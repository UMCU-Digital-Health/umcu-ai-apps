"""This module contains the SQLAlchemy models for the database.
The main function of this database is to store logging, feedback and evaluation data.
"""

from datetime import datetime

from sqlalchemy import Boolean, DateTime, ForeignKey, Integer, String, UniqueConstraint
from sqlalchemy.orm import (
    DeclarativeBase,
    Mapped,
    MappedAsDataclass,
    mapped_column,
    relationship,
)


class Base(DeclarativeBase, MappedAsDataclass):
    """Base class for all models."""

    pass


class Reference(Base):
    """Table that stores reference information.

    Attributes
    ----------
    id : int
        Primary key.
    reference_id : int
        Unique identifier for the reference.
    reference_description : str
        Description of the reference.
    project : str
        Project associated with the reference.
    department : str
        Department associated with the reference.
    loaded_at : datetime
        Timestamp when the reference was loaded.
    """

    __tablename__ = "reference"
    __table_args__ = {"schema": "llm_eval"}

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True, init=False)
    reference_id: Mapped[int] = mapped_column(Integer, unique=True)
    reference_description: Mapped[str] = mapped_column(String, nullable=True)
    project: Mapped[str] = mapped_column(String(50), index=True)
    department: Mapped[str] = mapped_column(String(50), index=True)
    loaded_at: Mapped[datetime] = mapped_column(
        DateTime, default_factory=datetime.now, init=False
    )

    # Relationships
    evaluation_item_relation: Mapped["EvaluationItem"] = relationship(
        back_populates="reference_relation", uselist=False, init=False
    )
    context_relation: Mapped["Context"] = relationship(
        back_populates="reference_relation", uselist=False, init=False
    )


class EvaluationItem(Base):
    """Table that stores the items that are evaluated, typically LLM responses.

    Attributes
    ----------
    id : int
        Primary key.
    reference_id : int
        Foreign key linking to the reference table.
    llm_response : str
        The response generated by the LLM.
    model : str
        The model used to generate the response.
    """

    __tablename__ = "evaluation_item"
    __table_args__ = {"schema": "llm_eval"}

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True, init=False)
    reference_id: Mapped[int] = mapped_column(
        Integer, ForeignKey(Reference.id), unique=True, init=False
    )
    llm_response: Mapped[str]
    model: Mapped[str] = mapped_column(String(10), nullable=True)

    # Relationships
    reference_relation: Mapped["Reference"] = relationship(
        back_populates="evaluation_item_relation", init=False
    )
    markings_relation: Mapped[list["Marking"]] = relationship(
        back_populates="evaluation_item_relation", init=False
    )
    assessment_usability_relation: Mapped["AssessmentUsability"] = relationship(
        back_populates="evaluation_item_relation", init=False
    )


class Context(Base):
    """Table that stores context information.

    Attributes
    ----------
    id : int
        Primary key.
    reference_id : int
        Foreign key linking to the reference table.
    context_text : str
        The context text (usually patient file data)
    """

    __tablename__ = "context"
    __table_args__ = {"schema": "llm_eval"}

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True, init=False)
    reference_id: Mapped[int] = mapped_column(
        Integer, ForeignKey(Reference.id), unique=True, init=False
    )
    context_text: Mapped[str]

    # Relationships
    reference_relation: Mapped["Reference"] = relationship(
        back_populates="context_relation", init=False
    )
    markings_relation: Mapped[list["Marking"]] = relationship(
        back_populates="context_relation", init=False
    )


class User(Base):
    """Table that stores user information.

    Attributes
    ----------
    id : int
        Primary key.
    email : str
        The email address of the user.
    """

    __tablename__ = "user"
    __table_args__ = {"schema": "llm_eval"}

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True, init=False)
    email: Mapped[str] = mapped_column(String(255), unique=True, index=True)

    # Relationships
    markings_relation: Mapped[list["Marking"]] = relationship(
        back_populates="user_relation", init=False
    )
    assessment_usabilities_relation: Mapped[list["AssessmentUsability"]] = relationship(
        back_populates="user_relation", init=False
    )
    user_access_relation: Mapped[list["UserAccess"]] = relationship(
        back_populates="user_relation", init=False
    )


class UserAccess(Base):
    """Table that stores user access information.

    Attributes
    ----------
    id : int
        Primary key.
    user_id : int
        Foreign key linking to the user table.
    project : str
        The project the user has access to.
    department : str
        The department the user has access to.
    """

    __tablename__ = "user_access"

    __table_args__ = (
        UniqueConstraint(
            "user_id", "project", "department", name="uq_user_project_department"
        ),
        {"schema": "llm_eval"},
    )

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True, init=False)
    user_id: Mapped[int] = mapped_column(Integer, ForeignKey(User.id), init=False)
    project: Mapped[str] = mapped_column(String(50))
    department: Mapped[str] = mapped_column(String(50))

    # Relationships
    user_relation: Mapped["User"] = relationship(
        back_populates="user_access_relation", init=False
    )


class Marking(Base):
    """Table that stores markings made.

    Attributes
    ----------
    id : int
        Primary key.
    user_id : int
        Foreign key linking to the user table.
    evaluation_item_id : int
        Foreign key linking to the evaluation item table.
    context_id : int
        Foreign key linking to the context table.
    marking_type : str
        The type of marking, e.g. missing, error, trivial or wording
    marking_text : str
        The text of the marking.
    marking_start : int
        The start position of the marking in the text.
    marking_end : int
        The end position of the marking in the text.
    timestamp : datetime
        The timestamp when the marking was made.
    is_severe : bool
        Indicates if the marking is severe.
    comment : str | None
        Optional comment associated with the marking.
    """

    __tablename__ = "marking"
    __table_args__ = {"schema": "llm_eval"}

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True, init=False)
    user_id: Mapped[int] = mapped_column(Integer, ForeignKey(User.id), init=True)
    evaluation_item_id: Mapped[int] = mapped_column(
        Integer, ForeignKey(EvaluationItem.id), init=True
    )
    context_id: Mapped[int] = mapped_column(Integer, ForeignKey(Context.id), init=True)
    marking_type: Mapped[str]
    marking_text: Mapped[str]
    marking_start: Mapped[int]
    marking_end: Mapped[int]
    timestamp: Mapped[datetime] = mapped_column(DateTime)
    is_severe: Mapped[bool] = mapped_column(Boolean, default=False)
    comment: Mapped[str | None] = mapped_column(String, nullable=True, default=None)

    # Relationships
    user_relation: Mapped["User"] = relationship(
        back_populates="markings_relation", init=False
    )
    evaluation_item_relation: Mapped["EvaluationItem"] = relationship(
        back_populates="markings_relation", init=False
    )
    context_relation: Mapped["Context"] = relationship(
        back_populates="markings_relation", init=False
    )


class AssessmentUsability(Base):
    """Table that stores usability assessments.

    Attributes
    ----------
    id : int
        Primary key.
    user_id : int
        Foreign key linking to the user table.
    evaluation_item_id : int
        Foreign key linking to the evaluation item table.
    usability_score : int
        The usability score given by the user.
    comments : str | None
        Optional comments associated with the assessment.
    timestamp : datetime
        The timestamp when the assessment was made.
    """

    __tablename__ = "assessment_usability"
    __table_args__ = {"schema": "llm_eval"}

    id: Mapped[int] = mapped_column(Integer, primary_key=True, index=True, init=False)
    user_id: Mapped[int] = mapped_column(Integer, ForeignKey(User.id), init=True)
    evaluation_item_id: Mapped[int] = mapped_column(
        Integer, ForeignKey(EvaluationItem.id), unique=True, init=True
    )
    usability_score: Mapped[int]
    comments: Mapped[str | None] = mapped_column(String, nullable=True)
    timestamp: Mapped[datetime] = mapped_column(DateTime)

    # Relationships
    user_relation: Mapped["User"] = relationship(
        back_populates="assessment_usabilities_relation", init=False
    )
    evaluation_item_relation: Mapped["EvaluationItem"] = relationship(
        back_populates="assessment_usability_relation", init=False
    )
